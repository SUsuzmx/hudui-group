/** key 或 icon 字段 → SVG path */
export function statusIconPath(iconOrKey) {
  return STATUS_ICONS[iconOrKey] || STATUS_ICONS.smile;
}

export function statusGradient(key, label) {
  const hasStatus = Boolean(key || (label && label !== '+ 状态'));
  if (!hasStatus) return '';
  return STATUS_GRADIENTS[key] || STATUS_GRADIENTS.custom;
}

/** 状态剩余时长文案（微信：N小时后将自动结束） */
export function statusRemaining(at, expiresHours = 24) {
  if (!at) return '';
  const end = Number(at) + (Number(expiresHours) || 24) * 3600_000;
  const left = end - Date.now();
  if (left <= 0) return '即将自动结束';
  const h = Math.max(1, Math.round(left / 3600_000));
  return `${h}小时后将自动结束`;
}
