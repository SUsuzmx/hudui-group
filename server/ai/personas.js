export function getPersonaById(id) {
  return personas.find((p) => p.id === id) || null;
}

export function personasForGroup(kind) {
  if (!kind || kind === 'main') {
    return personas.filter((p) => !p.groups || p.groups.includes('main') || !groupPersonas.some((g) => g.id === p.id));
  }
  return personas.filter((p) => !p.groups || p.groups.includes(kind));
}
